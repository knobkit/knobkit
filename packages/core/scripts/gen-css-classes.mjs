/*
 * Generates a `<name>.css.ts` beside every `<name>.css`: it imports the stylesheet and exports a
 * constant per class the sheet mentions. Views import the constant instead of writing a literal,
 * so naming a class is what loads its rules — they cannot drift apart, and a class no sheet
 * defines is a codegen error rather than an invisible unstyled element at runtime.
 *
 * A sheet that only *extends* a class defined elsewhere (`.pu-submit.pu-rec`) re-exports the name
 * from the defining sheet's module, so importing the modifier pulls the base too.
 *
 * Run via `pnpm gen:css`; `css-generated.test.ts` fails if the checked-in output is stale.
 */
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

/** Stylesheets loaded unconditionally by another package (core's styles.css rides render.tsx). */
export const AMBIENT_DIRS = [];

const camel = (cls) =>
  cls
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join("");

/** `defines` = classes given a rule of their own; `mentions` = every class named in any selector. */
export function parseSheet(css) {
  const defines = new Set();
  const mentions = new Set();
  for (const rule of css.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/([^{}]+)\{/g)) {
    const prelude = rule[1];
    if (/^\s*@/.test(prelude)) continue; // @layer / @media preludes aren't selectors
    for (const raw of prelude.split(",")) {
      const sel = raw.trim().replace(/::?[a-z-]+(\([^)]*\))?/g, "");
      const classes = [...sel.matchAll(/\.(pu-[a-zA-Z0-9_-]+)/g)].map((m) => m[1]);
      for (const c of classes) mentions.add(c);
      // ownership is the bare selector only: `textarea.pu-input` extends the primitive that
      // `.pu-input` defines, so it must not read as a second definition of it
      if (classes.length === 1 && sel.trim() === `.${classes[0]}`) defines.add(classes[0]);
    }
  }
  return { defines, mentions };
}

export function generate({ root, ambientDirs = [], write = true }) {
  const ambient = new Set();
  for (const dir of ambientDirs)
    for (const f of globSync(`${dir}/**/*.css`))
      for (const c of parseSheet(readFileSync(f, "utf8")).defines) ambient.add(c);

  const sheets = globSync(`${root}/**/*.css`).sort();
  const parsed = new Map(sheets.map((f) => [f, parseSheet(readFileSync(f, "utf8"))]));

  const owner = new Map(); // class -> defining sheet
  for (const [file, { defines }] of parsed)
    for (const c of defines) {
      const prev = owner.get(c);
      if (prev && prev !== file)
        throw new Error(`.${c} is defined twice: ${relative(root, prev)} and ${relative(root, file)}`);
      owner.set(c, file);
    }

  const written = [];
  for (const [file, { defines, mentions }] of parsed) {
    const base = file.slice(file.lastIndexOf("/") + 1);
    const lines = [`// Generated by scripts/gen-css-classes.mjs — do not edit.`, `import "./${base}";`, ""];
    const names = new Map();
    const add = (c) => {
      const n = camel(c);
      const clash = names.get(n);
      if (clash && clash !== c) throw new Error(`${n} maps to both .${clash} and .${c}`);
      names.set(n, c);
      return n;
    };

    for (const c of [...defines].sort()) lines.push(`export const ${add(c)} = ${JSON.stringify(c)};`);

    const foreign = [...mentions].filter((c) => !defines.has(c) && !ambient.has(c)).sort();
    for (const c of foreign) {
      const from = owner.get(c);
      if (!from) {
        // no sheet gives it a standalone rule: a marker/modifier that only means something in a
        // qualified selector (.pu-submit.pu-rec, [data-fill] … > .pu-field-grow). The sheet that
        // gives it meaning owns it — several may, and they agree on the string.
        lines.push(`export const ${add(c)} = ${JSON.stringify(c)};`);
        continue;
      }
      let spec = relative(dirname(file), from).replace(/\.css$/, ".css.js");
      if (!spec.startsWith(".")) spec = `./${spec}`;
      lines.push(`export { ${add(c)} } from ${JSON.stringify(spec)};`);
    }

    const out = `${file}.ts`;
    const body = lines.join("\n").replace(/\n+$/, "") + "\n";
    if (write) writeFileSync(out, body);
    written.push([out, body]);
  }
  return new Map(written);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const written = generate({ root: resolve("src"), ambientDirs: AMBIENT_DIRS.map((d) => resolve(d)) });
  console.log(`gen-css-classes: ${written.size} modules`);
}
